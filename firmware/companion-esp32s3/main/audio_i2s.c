/*
 * I2S audio.
 *   Mic:     INMP441 on J2/J3 (I2S RX, net SD) -> 16-bit PCM -> AUDIO_MIC (0x41)
 *            to the base.
 *   Speaker: 4 ohm 3 W driver on J6, behind U11 (MAX98357A class-D amp) whose
 *            DIN is net /ESP32/DIN (I2S TX), fed by AUDIO_TTS (0x40) chunks
 *            queued from wifi_udp.c. GATED OFF BY DEFAULT — see the TX gate note
 *            below.
 *
 * Net names on this board do NOT follow I2S roles, and reading them as if they
 * did is what caused the bug described under "the TX gate" below. Concretely:
 *   net /ESP32/DIN  is U11 pin 1, the AMPLIFIER's data input  = our DOUT = GPIO38
 *   net SD          is J2 pin 1, the MICROPHONE's data output = our DIN  = GPIO40
 * Only connectivity decides which is which. Every pin here comes from
 * CONFIG_KGN_I2S_*; see main/Kconfig.projbuild and PINMAP.md.
 *
 * ============================ I2S topology ============================
 *
 * The PCB gives the mic and the amp a SHARED bit clock and word select (nets
 * BCLK(38) / WS(39) — stale names, see below) and separate data lines. That is
 * one I2S peripheral in full duplex, not two controllers, and IDF 6.1 supports
 * it directly on the ESP32-S3:
 *
 *   - i2s_new_channel() with both a TX and an RX handle allocates the pair on
 *     one controller.
 *   - i2s_channel_init_std_mode() on the second of the pair notices that the
 *     BCLK pin, the WS pin, the sample rate and the total frame bits match the
 *     first, sets the controller's share-BCK/WS bit, and demotes the second
 *     channel to an internal slave so only one side drives the two clock pads.
 *     (esp_driver_i2s/i2s_common.c: i2s_channel_try_to_constitute_duplex.)
 *
 * What that costs us, and it is not negotiable in hardware:
 *
 *   - ONE sample rate for both directions (CONFIG_KGN_AUDIO_SAMPLE_RATE).
 *   - ONE slot width for both directions. Both are 32-bit slots here, so the
 *     frame is 2 x 32 = 64 bits and the two directions agree by construction.
 *     The INMP441 wants 32-bit slots anyway (24 data bits + 8 of padding), and
 *     matching the speaker to it is free, so 32/32 it is. The alternative —
 *     16-bit TX data inside a 32-bit slot — also pairs, but it makes the TX side
 *     depend on the left_align slot-placement bit for correctness, and that is
 *     one more thing that cannot be checked without hardware. A 16->32 shift in
 *     software costs 16000 shifts a second. That is the cheaper unknown to
 *     remove.
 *   - WHEN TX EXISTS, TX is initialised FIRST and therefore stays master. That is
 *     deliberate twice over: the driver's internal full-duplex slave needs
 *     mclk/bclk >= 6 on TX but only >= 4 on RX, and with mclk_multiple 384 we get
 *     exactly 6 either way, so neither ordering warns — but making TX the master
 *     also means BCLK and WS keep running as long as playback is up.
 *
 * The ESP32-S3 camera (DVP) path uses the LCD_CAM peripheral, not I2S, so
 * holding an I2S controller here does not cost the pending camera decision
 * anything.
 *
 * ===================== The TX gate, and why it exists =====================
 *
 * CONFIG_KGN_AUDIO_TX_ENABLE gates the whole speaker path and defaults to n.
 *
 * KGN_I2S_DOUT and KGN_I2S_DIN were originally swapped (40/38 instead of
 * 38/40), so nothing drove U11 pin 1. The TX gate keeps the data line defined
 * during staged bring-up. A later PCB and bench check found U11 pin 4 SD_MODE
 * tied to GND, holding the amplifier in shutdown regardless of I2S data.
 * The old hypothesis that floating DIN caused U11 to overheat near SW3 is
 * therefore unlikely. J6 cannot play until SD_MODE is isolated from GND and
 * enabled, or an external I2S amplifier is connected.
 *
 * What the gate does when it is OFF (the default):
 *   - No TX channel is allocated at all. i2s_new_channel() is called with a NULL
 *     tx handle, so the DOUT pad is never claimed by the I2S peripheral.
 *   - CONFIG_KGN_I2S_DOUT is instead parked as a plain GPIO driven LOW, so U11
 *     sees a constant zero sample rather than a floating input. Zero data on a
 *     MAX98357A is silence, which is the cold state; floating is not.
 *   - THE MIC STILL WORKS, and this is the part that needed checking rather than
 *     assuming. BCLK/WS used to be generated by the TX side, so with TX gone the
 *     RX channel has to become the clock master. It does, and IDF 6.1 supports it
 *     directly: i2s_new_channel() only requires one of the two handles
 *     (I2S_NULL_POINTER_CHECK on `tx_handle || rx_handle`), and in
 *     i2s_std_set_gpio() the bit-clock and word-select pads are assigned from
 *     i2s_periph_signal[].m_rx_bck_sig / m_rx_ws_sig with is_input false for a
 *     master RX channel — i.e. the RX side drives the two clock pads itself. The
 *     clock maths is also unchanged: with no TX channel there is no full-duplex
 *     slave to satisfy, and mclk_multiple 384 still divides (6.144 MHz mclk /
 *     1.024 MHz bclk = 6, integer).
 *   - AUDIO_TTS chunks are still dequeued and freed (they would otherwise leak),
 *     and a CTRL SELFTEST logs that the TX path is disabled instead of silently
 *     doing nothing.
 *
 * When the gate is ON, TX is enabled once at boot and left enabled, with
 * auto_clear on so the DMA emits zeros when there is nothing to play.
 *
 * =================== The BCLK / WS assignment is RESOLVED ===================
 *
 * Earlier revisions of this comment said BCLK/WS were the most likely wrong pins
 * in the project, because the schematic net labels read BCLK(38) / WS(39) while
 * the nets land on the pads for IO39 and IO41. That is settled: the "(38)"/"(39)"
 * suffixes are stale label text from an earlier pin assignment, not copper.
 * Connectivity is unambiguous — pad 32 = IO39 carries the bit clock, pad 34 =
 * IO41 carries word select. BCLK = 39, WS = 41, no bench verification required.
 *
 * Nothing in this file names a GPIO. Every pin comes from CONFIG_KGN_I2S_*, so
 * any future correction is menuconfig plus a reflash, not an edit here. The boot
 * log still prints the pins and the clock frequencies.
 *
 * ============================== Fail soft ==============================
 *
 * Every failure path here logs once and leaves the subsystem off. A missing mic,
 * a dead amp, an I2S init error or a heap failure must not cost Wi-Fi, UDP,
 * telemetry, the display or the servo — the board is half-wired on a bench.
 * Note that neither the mic nor the amp can be detected: I2S has no readback,
 * so "absent" and "working" look identical from here. Only host-side failures
 * (channel alloc, mode init, buffer alloc, task create) are caught.
 *
 * TODO(kogane): VAD / AGC on the capture path so the mic stream is not 256
 * kbit/s of room noise whenever the base is listening.
 * TODO(kogane): Opus. PROTOCOL.md deliberately specifies PCM only for now —
 * a codec that cannot be verified is worse than a format that can.
 */
